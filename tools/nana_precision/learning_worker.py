"""Same executed G/Kernel learning comparison, isolated synthetic Subjects only."""
import json
import sys
from pathlib import Path
import random


def main():
    source, root, seed = Path(sys.argv[1]), Path(sys.argv[2]), int(sys.argv[3])
    sys.path.insert(0,str(source))
    sys.path.insert(0,str(source/'src'))
    from nana_core.continuity.open_agency.learning import LearningService,LearningSpec,LearningCase
    from nana_core.continuity.records import RecordService
    from tests.open_autonomy.helpers import fresh,objective,configure,cue,send,advance
    from tests.open_autonomy.test_learning import start_learning
    rng=random.Random(seed)
    # Hidden evaluation/new-context inputs are generated by the experiment host;
    # proposer sees only LearningProblem.practice, never these answer tables.
    inputs=[[rng.randint(1,15)+.25,rng.randint(1,15)+.5] for _ in range(4)]
    cases=[LearningCase(case_id='c'+str(i),context='practice' if i==0 else 'heldout' if i==1 else 'new-context',data=data,expected=sum(data)) for i,data in enumerate(inputs[:3])]
    kwargs=dict(learning_key='learn.precision',domain='numbers',baseline_method='NAIVE_SUM',hypotheses=('NAIVE_SUM','NUMERIC_SUM'),practice=(cases[0],),evaluation=(cases[1],),transfer=(cases[2],))
    upgraded='hypothesis_policy' in LearningSpec.model_fields
    if upgraded:kwargs['hypothesis_policy']='PRACTICE_COMPARE'
    spec=LearningSpec(**kwargs)
    with fresh(root/'s'/'self.db') as runtime:
        service=LearningService(runtime.store,runtime.authority,(spec,),privacy_classes=('PERSONAL',),scopes=('lab',));runtime.work.open_learning=service
        start_learning(runtime,spec)
        job=runtime.store.db.execute("SELECT * FROM jobs WHERE work_kind='LEARNING'").fetchone();body=RecordService(runtime.store).read(job['record_id'])['payload']
        obj=objective('precision.later',method='NAIVE_SUM',expected=sum(inputs[3]))
        port=configure(runtime,root/'w'/'later.fixture.json',(obj,));runtime.work.agency.learning=service
        port.seed_observation(obj.operators[0].resource,inputs[3]);send(runtime,'later',(cue(runtime,obj),));runtime.step();advance(runtime,6)
        goal=runtime.store.all('goals')[0]
        result={'source':str(source),'selection':'PRACTICE_COMPARE' if upgraded else 'PROPOSER_ONLY','learning_state':job['state'],'selected_method':body['selected_method'],'results':{key:{k:value[k] for k in ('checked','passed','all_passed')} for key,value in body['results'].items()},'later_goal':goal['state'],'later_observed_output':port._load().get('resources',{}).get(obj.operators[-1].resource),'later_independent_expected':sum(inputs[3]),'seed':seed,'new_provider_calls':0,'private_data':False,'scope':'EXECUTED_SYNTHETIC_CORE_G_AND_KERNEL_NOT_OPEN_WORLD_LEARNING'}
        print(json.dumps(result))


if __name__=='__main__':main()
