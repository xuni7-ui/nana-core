import json
import pytest
from nana_core.storage import Store,canonical
from nana_core.contracts import CoreError,Observation
from nana_core.initiative import GoalCandidate
from nana_core.integration.initiative import InitiativeHostGate

def test_host_initiative_dedup_restart_charter_and_grant_barrier(tmp_path):
    db=tmp_path/'core.db'
    with Store(db) as s:
        identity=s.identity;ev=s.ingest(Observation(source_namespace='synthetic.host',object_id='care',kind='unrelated',raw_text='Fictional long-term context and present wish'))
        c=GoalCandidate(purpose='Consider caring dialogue',intent='dialogue',evidence_event_ids=(ev,),need=.8,importance=.7,urgency=.3,confidence=.9,disturbance=.1,user_requests_discretion=True)
        g=InitiativeHostGate(s);key,body=g.propose_and_evaluate(c)
        assert body['state']=='ACCEPTED' and body['user_preference_considered'] and body['charter']==json.loads(identity['body_json'])['charter']
        assert g.propose_and_evaluate(c)[0]==key and len(s.all('jobs'))==1
        blocked=c.model_copy(update={'purpose':'Draft an authorized reading task','intent':'reading_card','required_capability':'reading.source.read','resource':'source://synthetic/a'})
        assert g.propose_and_evaluate(blocked)[1]['reason']=='SHADOW_BLOCKED'
        with pytest.raises(CoreError,match='SHADOW_BLOCKED'):g.activate(key)
        assert not s.all('actions') and not s.all('grants') and not s.all('budgets')
    with Store(db) as s:
        assert s.identity==identity and InitiativeHostGate(s).propose_and_evaluate(c)[1]==body and len(s.all('jobs'))==1

def test_relationship_and_promise_are_persisted_claims_not_new_persona(tmp_path):
    db=tmp_path/'s.db'
    with Store(db) as s:
        identity=s.identity
        eid=s.ingest(Observation(source_namespace='synthetic.relationship',object_id='1',kind='unrelated',raw_text='Fictional sister self-identifies and a shared reading promise'))
        claims=[{'subject':'synthetic:sister','predicate':'address_as','value':'姐姐'},
            {'subject':identity['identity_id'],'predicate':'relationship','value':'synthetic:sister'},
            {'subject':identity['identity_id'],'predicate':'self_preference','value':'source-backed reading'},
            {'subject':identity['identity_id'],'predicate':'unfulfilled_promise','value':'read a synthetic paper together'},
            {'subject':identity['identity_id'],'predicate':'long_term_goal','value':'retain shared fictional experiences'}]
        for i,claim in enumerate(claims):
            with s.transaction('synthetic.relationship_claim') as tx:
                tx.put('memory_items',{'memory_id':'synthetic:relation:'+str(i),'kind':'CLAIM','status':'ACTIVE','created_event_id':tx.event_id,
                    'body_json':canonical({'claim':claim,'source_refs':[{'event_id':eid,'coverage':'FULL'}],'assessment':'UNASSESSED','origin':'operator fixture; not regenerated by model'})})
        before=s.snapshot()
    with Store(db) as s:
        assert s.identity==identity and s.snapshot()==before
        assert all(json.loads(s.one('memory_items','synthetic:relation:'+str(i))['body_json'])['claim']==claim for i,claim in enumerate(claims))
        assert not s.all('grants') and not s.all('strategies')
